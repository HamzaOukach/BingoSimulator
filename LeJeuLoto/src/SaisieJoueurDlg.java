    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
     JFileChooser chooser = new JFileChooser();
        int retour = chooser.showOpenDialog(this);
        if(retour == JFileChooser.APPROVE_OPTION) {
            File fichier = chooser.getSelectedFile();
            photo = new ImageIcon(fichier.getPath());
        } else if(retour == JFileChooser.ERROR_OPTION) {
            JOptionPane.showMessageDialog(this, "Erreur lors de l'ouverture du fichier.", "Erreur", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_jButton2ActionPerformed
