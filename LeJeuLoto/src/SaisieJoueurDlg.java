    private void getInfos() {
    String pseudo = jTextField1.getText();
    String soldeStr = jTextField2.getText();
    double solde = 0.0;
    if (!soldeStr.isEmpty()) {
        try {
            solde = Double.parseDouble(soldeStr);
        } catch(NumberFormatException e) {
            // handle the error
        }
    }
    Color couleur1 = jPanel6.getBackground(); 
    if(couleur1 == null) {
        couleur1 = Color.WHITE; 
    }
    

    
    joueur.setPseudo(pseudo);
    joueur.setSolde(solde);
    joueur.setCouleur(couleur1);
    joueur.setPhoto(new ImageIcon("path/to/photo.png"));
}

  


   

